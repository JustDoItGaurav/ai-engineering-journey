# ============================================================
# NUMPY MATHEMATICAL OPERATIONS IN PYTHON
# ============================================================

# NumPy provides powerful mathematical operations that work
# directly on arrays without using loops.

import numpy as np

# ============================================================
# SAMPLE ARRAY
# ============================================================

arr = np.array([10, 20, 30, 40, 50])

print(arr)

# ============================================================
# ADDITION
# ============================================================

arr = np.array([1, 2, 3, 4])

result = arr + 10

print(result)

# Output:
# [11 12 13 14]

# ============================================================
# SUBTRACTION
# ============================================================

arr = np.array([10, 20, 30, 40])

result = arr - 5

print(result)

# Output:
# [ 5 15 25 35 ]

# ============================================================
# MULTIPLICATION
# ============================================================

arr = np.array([1, 2, 3, 4])

result = arr * 2

print(result)

# Output:
# [2 4 6 8]

# ============================================================
# DIVISION
# ============================================================

arr = np.array([10, 20, 30, 40])

result = arr / 2

print(result)

# Output:
# [ 5. 10. 15. 20.]

# ============================================================
# FLOOR DIVISION
# ============================================================

arr = np.array([10, 20, 30])

result = arr // 3

print(result)

# Output:
# [3 6 10]

# ============================================================
# MODULUS (REMAINDER)
# ============================================================

arr = np.array([10, 20, 30])

result = arr % 3

print(result)

# Output:
# [1 2 0]

# ============================================================
# POWER
# ============================================================

arr = np.array([1, 2, 3, 4])

result = arr ** 2

print(result)

# Output:
# [ 1  4  9 16 ]

# ============================================================
# ARRAY + ARRAY
# ============================================================

arr1 = np.array([1, 2, 3])

arr2 = np.array([4, 5, 6])

print(arr1 + arr2)

# Output:
# [5 7 9]

# ============================================================
# ARRAY - ARRAY
# ============================================================

arr1 = np.array([10, 20, 30])

arr2 = np.array([1, 2, 3])

print(arr1 - arr2)

# Output:
# [ 9 18 27 ]

# ============================================================
# ARRAY * ARRAY
# ============================================================

arr1 = np.array([1, 2, 3])

arr2 = np.array([4, 5, 6])

print(arr1 * arr2)

# Output:
# [ 4 10 18 ]

# ============================================================
# ARRAY / ARRAY
# ============================================================

arr1 = np.array([10, 20, 30])

arr2 = np.array([2, 4, 5])

print(arr1 / arr2)

# Output:
# [5. 5. 6.]

# ============================================================
# ABSOLUTE VALUE
# ============================================================

arr = np.array([-10, -20, 30, -40])

print(np.abs(arr))

# Output:
# [10 20 30 40]

# ============================================================
# SQUARE ROOT
# ============================================================

arr = np.array([1, 4, 9, 16, 25])

print(np.sqrt(arr))

# Output:
# [1. 2. 3. 4. 5.]

# ============================================================
# SQUARE
# ============================================================

arr = np.array([1, 2, 3, 4])

print(np.square(arr))

# Output:
# [ 1  4  9 16 ]

# ============================================================
# EXPONENTIAL VALUES
# ============================================================

arr = np.array([1, 2, 3])

print(np.exp(arr))

# Output:
# e^1, e^2, e^3

# ============================================================
# LOGARITHM
# ============================================================

arr = np.array([1, 10, 100])

print(np.log(arr))

# Natural Log

print(np.log10(arr))

# Base 10 Log

# ============================================================
# TRIGONOMETRIC FUNCTIONS
# ============================================================

angles = np.array([0, 30, 45, 60, 90])

radians = np.radians(angles)

print(np.sin(radians))
print(np.cos(radians))
print(np.tan(radians))

# ============================================================
# ROUNDING VALUES
# ============================================================

arr = np.array([1.234, 2.567, 3.891])

print(np.round(arr, 2))

# Output:
# [1.23 2.57 3.89]

# ============================================================
# CEILING VALUES
# ============================================================

arr = np.array([1.2, 2.3, 3.8])

print(np.ceil(arr))

# Output:
# [2. 3. 4.]

# ============================================================
# FLOOR VALUES
# ============================================================

arr = np.array([1.2, 2.8, 3.9])

print(np.floor(arr))

# Output:
# [1. 2. 3.]

# ============================================================
# SUM OF ARRAY
# ============================================================

arr = np.array([10, 20, 30, 40])

print(np.sum(arr))

# Output:
# 100

# ============================================================
# PRODUCT OF ARRAY
# ============================================================

arr = np.array([1, 2, 3, 4])

print(np.prod(arr))

# Output:
# 24

# ============================================================
# CUMULATIVE SUM
# ============================================================

arr = np.array([10, 20, 30, 40])

print(np.cumsum(arr))

# Output:
# [10 30 60 100]

# ============================================================
# CUMULATIVE PRODUCT
# ============================================================

arr = np.array([1, 2, 3, 4])

print(np.cumprod(arr))

# Output:
# [ 1  2  6 24 ]

# ============================================================
# MAXIMUM VALUE
# ============================================================

arr = np.array([10, 80, 30, 90, 50])

print(np.max(arr))

# Output:
# 90

# ============================================================
# MINIMUM VALUE
# ============================================================

arr = np.array([10, 80, 30, 90, 50])

print(np.min(arr))

# Output:
# 10

# ============================================================
# INDEX OF MAXIMUM VALUE
# ============================================================

arr = np.array([10, 80, 30, 90, 50])

print(np.argmax(arr))

# Output:
# 3

# ============================================================
# INDEX OF MINIMUM VALUE
# ============================================================

arr = np.array([10, 80, 30, 90, 50])

print(np.argmin(arr))

# Output:
# 0

# ============================================================
# OPERATIONS ON 2D ARRAYS
# ============================================================

arr = np.array([
    [10, 20, 30],
    [40, 50, 60]
])

print(np.sum(arr))
print(np.max(arr))
print(np.min(arr))

# ============================================================
# ROW-WISE SUM
# ============================================================

arr = np.array([
    [10, 20, 30],
    [40, 50, 60]
])

print(np.sum(arr, axis=1))

# Output:
# [ 60 150 ]

# ============================================================
# COLUMN-WISE SUM
# ============================================================

arr = np.array([
    [10, 20, 30],
    [40, 50, 60]
])

print(np.sum(arr, axis=0))

# Output:
# [50 70 90]

# ============================================================
# PRACTICAL EXAMPLE 1
# STUDENT MARKS
# ============================================================

marks = np.array([80, 75, 90, 95, 85])

print("Total Marks:", np.sum(marks))
print("Highest Marks:", np.max(marks))
print("Lowest Marks:", np.min(marks))

# ============================================================
# PRACTICAL EXAMPLE 2
# SALES DATA
# ============================================================

sales = np.array([1000, 1200, 1500, 1800])

print("Total Sales:", np.sum(sales))
print("Average Sales:", np.mean(sales))

# ============================================================
# PRACTICAL EXAMPLE 3
# TEMPERATURE DATA
# ============================================================

temperature = np.array([28, 30, 35, 32, 29])

print("Maximum Temperature:", np.max(temperature))
print("Minimum Temperature:", np.min(temperature))

