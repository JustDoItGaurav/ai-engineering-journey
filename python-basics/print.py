# ============================================================
# PRINTING IN PYTHON
# ============================================================

# Simple text output
print("Hello World")

# Printing numbers
print(21)

# Printing decimal numbers
print(5.8)

# Printing boolean values
print(True)

# ------------------------------------------------------------
# Printing multiple values
# ------------------------------------------------------------

print("Hello", "World")

# ------------------------------------------------------------
# Using variables
# ------------------------------------------------------------

name = "Gaurav"
age = 21

print(name)
print(age)

# ------------------------------------------------------------
# Printing variables with text
# ------------------------------------------------------------

print("My name is", name)
print("My age is", age)

# ------------------------------------------------------------
# Using f-strings (Recommended)
# ------------------------------------------------------------

print(f"Hello, I am {name} and my age is {age}.")

# ------------------------------------------------------------
# Printing on the same line
# ------------------------------------------------------------

print("Python", end=" ")
print("Programming")

# ------------------------------------------------------------
# Custom separator
# ------------------------------------------------------------

print("Python", "AI", "ML", sep=" | ")

# ------------------------------------------------------------
# Multi-line printing
# ------------------------------------------------------------

print("""
Name: Gaurav
Age: 21
Learning: Python
""")

